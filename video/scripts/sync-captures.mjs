// Copies the prepared clips (media/captures/R*.mp4 + clips.json) into public/captures and writes src/captures.generated.ts.
// A clip that is missing stays null and renders as a labelled slot.
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const src = resolve(here, "../../media/captures");
const dst = resolve(here, "../public/captures");
const keys = ["R1-wifi", "R2-ask", "R3-verify", "R4-redact", "R5-leak"];

rmSync(dst, { recursive: true, force: true });
mkdirSync(dst, { recursive: true });
const meta = existsSync(join(src, "clips.json")) ? JSON.parse(readFileSync(join(src, "clips.json"), "utf8")) : {};
const out = {};
for (const k of keys) {
  const f = `${k}.mp4`;
  if (existsSync(join(src, f))) {
    cpSync(join(src, f), join(dst, f));
    out[k] = { file: `captures/${f}`, ...(meta[k] ?? {}) };
  } else out[k] = null;
}
writeFileSync(
  resolve(here, "../src/captures.generated.ts"),
  `// Generated by scripts/sync-captures.mjs. Do not edit: run \`npm run sync\`.\n` +
    `export type SpeedSpan = { from: number; to: number; speed: number };\n` +
    `export type Clip = { file: string; seconds?: number; aspect?: number; speedSpans?: SpeedSpan[]; marks?: Record<string, number> } | null;\n` +
    `export const clips: Record<string, Clip> = ${JSON.stringify(out, null, 2)};\n`
);
const have = keys.filter((k) => out[k]);
console.log(`clips found: ${have.length ? have.join(", ") : "none (slots will render)"}`);
